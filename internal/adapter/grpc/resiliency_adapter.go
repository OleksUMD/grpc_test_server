package grpc

import (
	"context"
	"fmt"
	"io"
	"log"

	dresl "github.com/OleksUMD/grpc_test_server/internal/application/resiliency"
	resl "github.com/OleksUMD/proto-example/protogen/go/resiliency"
	"google.golang.org/grpc"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/metadata"
	"google.golang.org/grpc/status"
)

func generateErrStatus(statusCode uint32) error {
	str := "Generated by server"
	if sc, ok := dresl.StatusCodeMap[statusCode]; ok && sc == codes.OK {
		return nil
	}
	if sc, ok := dresl.StatusCodeMap[statusCode]; ok {
		return status.New(sc, str).Err()
	}
	return status.New(codes.Internal, str).Err()
}

func (a *GrpcAdapter) UnaryResiliency(ctx context.Context, req *resl.ResiliencyRequest) (*resl.ResiliencyResponse, error) {
	log.Println("UnaryResiliency called")
	meta, ok := metadata.FromIncomingContext(ctx)
	if !ok {
		fmt.Println("Metadata is not presented in the request")
	} else {
		fmt.Println(meta.String())
		for k, v := range meta {
			fmt.Println(k, " : ", v)
		}
	}
	headerMeta := metadata.Pairs(
		"First-Header-Meta", "Meta-1",
		"Second-Header-Meta", "Meta-2",
	)
	grpc.SendHeader(ctx, headerMeta)
	str, sts := a.resiliencyService.GenerateResiliency(req.MinDelaySeconds, req.MaxDelaySeconds, req.StatusCodes)
	if errStatus := generateErrStatus(sts); errStatus != nil {
		return nil, errStatus
	}
	return &resl.ResiliencyResponse{
		DummyString: str,
	}, nil
}

func (a *GrpcAdapter) ServerStreamingResiliency(req *resl.ResiliencyRequest, stream grpc.ServerStreamingServer[resl.ResiliencyResponse]) error {
	log.Println("ServerStreamingResiliency called")
	ctx := stream.Context()
	for {
		select {
		case <-ctx.Done():
			log.Println("Client cancelled request")
			return nil
		default:
			str, sts := a.resiliencyService.GenerateResiliency(req.MinDelaySeconds, req.MaxDelaySeconds, req.StatusCodes)
			if errStatus := generateErrStatus(sts); errStatus != nil {
				return errStatus
			}
			stream.Send(&resl.ResiliencyResponse{
				DummyString: str,
			})
		}
	}
}

func (a *GrpcAdapter) ClientStreamingResiliency(stream grpc.ClientStreamingServer[resl.ResiliencyRequest, resl.ResiliencyResponse]) error {
	log.Println("ClientStreamingResiliency called")
	i := 0
	for {
		req, err := stream.Recv()
		if err == io.EOF {
			res := resl.ResiliencyResponse{
				DummyString: fmt.Sprintf("Received %d requests from client", i),
			}
			return stream.SendAndClose(&res)
		}
		if req != nil {
			_, sts := a.resiliencyService.GenerateResiliency(req.MinDelaySeconds, req.MaxDelaySeconds, req.StatusCodes)
			if errStatus := generateErrStatus(sts); errStatus != nil {
				return errStatus
			}
		}
		i++
	}
}

func (a *GrpcAdapter) BiStreamingResiliency(stream grpc.BidiStreamingServer[resl.ResiliencyRequest, resl.ResiliencyResponse]) error {
	log.Println("BiStreamingResiliency called")
	ctx := stream.Context()
	for {
		select {
		case <-ctx.Done():
			log.Println("Client cancelled request")
			return nil
		default:
			req, err := stream.Recv()
			if err == io.EOF {
				return nil
			}
			if err != nil {
				log.Fatalf("Error while reading from client : %v\n", err)
			}
			str, sts := a.resiliencyService.GenerateResiliency(req.MinDelaySeconds, req.MaxDelaySeconds, req.StatusCodes)
			if errStatus := generateErrStatus(sts); errStatus != nil {
				return errStatus
			}
			err = stream.Send(&resl.ResiliencyResponse{
				DummyString: str,
			})
			if err != nil {
				log.Fatalf("error while writing to client : %v\n", err)
			}
		}
	}
}
